"""Generate mountain ranges for the sunset scene → ../ranges.js

Usage:  python3 tools/mountains.py

Each range has four layers (far, mid, near, ground) as SVG path data for a
1600x1000 viewBox. Ridges use midpoint displacement, shaped by an envelope
that dips near the centre (x=800) so the sun sets into a valley.
Range 1 keeps the original hand-picked seeds; the rest are randomised.
"""
import math
import random
from pathlib import Path

COUNT = 20
OUT = Path(__file__).resolve().parent.parent / "ranges.js"

# base settings per layer (far → near)
BASE = {
    "far":    dict(base=640, height=260, rough=0.55, levels=7, smooth_k=0, valley_depth=0.6,  valley_width=260, curve=False),
    "mid":    dict(base=680, height=170, rough=0.52, levels=6, smooth_k=0, valley_depth=0.55, valley_width=320, curve=False),
    "near":   dict(base=720, height=100, rough=0.45, levels=4, smooth_k=0, valley_depth=0.5,  valley_width=380, curve=True),
    "ground": dict(base=770, height=45,  rough=0.4,  levels=3, smooth_k=0, valley_depth=0.3,  valley_width=500, curve=True),
}
FIRST_SEEDS = {"far": 11, "mid": 21, "near": 5, "ground": 3}


def midpoint(n_levels, rough, rng):
    pts = [0.0, 0.0]
    amp = 1.0
    for _ in range(n_levels):
        nxt = []
        for a, b in zip(pts, pts[1:]):
            nxt += [a, (a + b) / 2 + rng.uniform(-amp, amp)]
        nxt.append(pts[-1])
        pts = nxt
        amp *= rough
    lo, hi = min(pts), max(pts)
    return [(p - lo) / (hi - lo) for p in pts]  # normalised 0..1


def smooth(vals, k):
    if k <= 0:
        return vals
    return [sum(vals[max(0, i - k): i + k + 1]) / len(vals[max(0, i - k): i + k + 1]) for i in range(len(vals))]


def layer(seed, base, height, rough, levels, smooth_k, valley_depth, valley_width, curve):
    v = smooth(midpoint(levels, rough, random.Random(seed)), smooth_k)
    n = len(v)
    xs = [-40 + 1680 * i / (n - 1) for i in range(n)]
    ys = [base - height * h * (1 - valley_depth * math.exp(-((x - 800) / valley_width) ** 2))
          for x, h in zip(xs, v)]
    if curve:
        # Catmull-Rom → cubic Béziers for soft rolling hills
        P = list(zip(xs, ys))
        d = f"M -40 1000 L {xs[0]:.0f} {ys[0]:.0f}"
        for i in range(len(P) - 1):
            p0, p1, p2, p3 = P[max(0, i - 1)], P[i], P[i + 1], P[min(len(P) - 1, i + 2)]
            c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
            c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
            d += f" C {c1[0]:.0f} {c1[1]:.0f}, {c2[0]:.0f} {c2[1]:.0f}, {p2[0]:.0f} {p2[1]:.0f}"
    else:
        d = "M -40 1000 " + " ".join(f"L {x:.0f} {y:.0f}" for x, y in zip(xs, ys))
    return d + " L 1640 1000 Z"


def build_range(i):
    if i == 0:
        return {k: layer(FIRST_SEEDS[k], **BASE[k]) for k in BASE}
    rng = random.Random(1000 + i)
    out = {}
    for k, cfg in BASE.items():
        cfg = dict(cfg)
        cfg["height"] *= rng.uniform(0.8, 1.2)
        cfg["valley_depth"] = min(0.8, cfg["valley_depth"] * rng.uniform(0.75, 1.25))
        cfg["valley_width"] *= rng.uniform(0.8, 1.25)
        if not cfg["curve"]:
            cfg["rough"] = rng.uniform(cfg["rough"] - 0.05, cfg["rough"] + 0.05)
        out[k] = layer(rng.randrange(1 << 30), **cfg)
    return out


def main():
    ranges = [build_range(i) for i in range(COUNT)]
    lines = ["// Generated by tools/mountains.py — edit that script and re-run it instead of editing this file.",
             "const RANGES = ["]
    for r in ranges:
        lines.append("  {")
        lines += [f'    {k}: "{d}",' for k, d in r.items()]
        lines.append("  },")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {COUNT} ranges to {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
