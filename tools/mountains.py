"""Generate the "mountains" range (the site's default) → ../ranges.js

Usage:  python3 tools/mountains.py

Four layers (far, mid, near, ground) as SVG path data for a 1600x1000
viewBox. Ridges use midpoint displacement, shaped by an envelope that dips
near the centre (x=800) so the sun sets into a valley. Fixed seeds, so it
always produces the same shapes.

tools/peaks/skyline.py also uses BASE and layer() from here to generate the
hills in front of the real peaks.
"""
import math
import random
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "ranges.js"
NAME = "mountains"  # what the menu shows

# base settings per layer (far → near). Shapes are drawn at their final resting
# place: the sun (r=220) is pinned at the screen centre (800, 500), and the far
# valley bottoms out around y=420, so only the top of the sun shows above it.
BASE = {
    "far":    dict(base=420, height=260, rough=0.55, levels=7, smooth_k=0, valley_depth=0.6,  valley_width=260, curve=False),
    "mid":    dict(base=460, height=170, rough=0.52, levels=6, smooth_k=0, valley_depth=0.55, valley_width=320, curve=False),
    "near":   dict(base=500, height=100, rough=0.45, levels=4, smooth_k=0, valley_depth=0.5,  valley_width=380, curve=True),
    "ground": dict(base=550, height=45,  rough=0.4,  levels=3, smooth_k=0, valley_depth=0.3,  valley_width=500, curve=True),
}
SEEDS = {"far": 11, "mid": 21, "near": 5, "ground": 3}


def midpoint(n_levels, rough, rng):
    pts = [0.0, 0.0]
    amp = 1.0
    for _ in range(n_levels):
        nxt = []
        for a, b in zip(pts, pts[1:]):
            nxt += [a, (a + b) / 2 + rng.uniform(-amp, amp)]
        nxt.append(pts[-1])
        pts = nxt
        amp *= rough
    lo, hi = min(pts), max(pts)
    return [(p - lo) / (hi - lo) for p in pts]  # normalised 0..1


def smooth(vals, k):
    if k <= 0:
        return vals
    return [sum(vals[max(0, i - k): i + k + 1]) / len(vals[max(0, i - k): i + k + 1]) for i in range(len(vals))]


def layer(seed, base, height, rough, levels, smooth_k, valley_depth, valley_width, curve):
    v = smooth(midpoint(levels, rough, random.Random(seed)), smooth_k)
    n = len(v)
    xs = [-40 + 1680 * i / (n - 1) for i in range(n)]
    ys = [base - height * h * (1 - valley_depth * math.exp(-((x - 800) / valley_width) ** 2))
          for x, h in zip(xs, v)]
    if curve:
        # Catmull-Rom → cubic Béziers for soft rolling hills
        P = list(zip(xs, ys))
        d = f"M -40 1000 L {xs[0]:.0f} {ys[0]:.0f}"
        for i in range(len(P) - 1):
            p0, p1, p2, p3 = P[max(0, i - 1)], P[i], P[i + 1], P[min(len(P) - 1, i + 2)]
            c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
            c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
            d += f" C {c1[0]:.0f} {c1[1]:.0f}, {c2[0]:.0f} {c2[1]:.0f}, {p2[0]:.0f} {p2[1]:.0f}"
    else:
        d = "M -40 1000 " + " ".join(f"L {x:.0f} {y:.0f}" for x, y in zip(xs, ys))
    return d + " L 1640 1000 Z"


def main():
    lines = ["// Generated by tools/mountains.py — edit that script and re-run it instead of editing this file.",
             "const RANGES = [",
             "  {",
             f'    name: "{NAME}",']
    lines += [f'    {k}: "{layer(SEEDS[k], **BASE[k])}",' for k in BASE]
    lines += ["  },", "];"]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
